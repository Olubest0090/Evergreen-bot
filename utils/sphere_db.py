"""Database helpers for the Federal Sphere module.

Uses the already-initialized Supabase REST session from utils.database so the
bot keeps one shared HTTP session and one set of credentials.
"""
from __future__ import annotations
from utils import database


def _base():
    if database._session is None or not database._base_url:
        raise RuntimeError("Supabase database client has not been initialized")
    return database._base_url + "/rest/v1"


def _headers(prefer: str | None = None):
    return {"Prefer": prefer} if prefer else {}


async def _check(resp, allowed=(200, 201, 204)):
    if resp.status not in allowed:
        raise RuntimeError(f"Supabase error {resp.status}: {await resp.text()}")


async def list_alliances(guild_id: int) -> list[dict]:
    async with database._session.get(_base()+"/sphere_alliances", params={"guild_id":f"eq.{guild_id}","select":"*","order":"alliance_name.asc"}) as r:
        await _check(r, (200,))
        return await r.json()


async def add_alliance(guild_id: int, alliance_id: int, alliance_name: str, score: float | None = None):
    payload={"guild_id":guild_id,"alliance_id":alliance_id,"alliance_name":alliance_name,"score":score,"active":True}
    async with database._session.post(_base()+"/sphere_alliances?on_conflict=guild_id,alliance_id",json=payload,headers=_headers("resolution=merge-duplicates,return=minimal")) as r:
        await _check(r)


async def remove_alliance(guild_id: int, alliance_id: int):
    # Soft removal preserves historical war and intelligence records.
    async with database._session.patch(_base()+"/sphere_alliances",params={"guild_id":f"eq.{guild_id}","alliance_id":f"eq.{alliance_id}"},json={"active":False}) as r:
        await _check(r)


async def get_config(guild_id: int) -> dict | None:
    async with database._session.get(_base()+"/sphere_config",params={"guild_id":f"eq.{guild_id}","select":"*"}) as r:
        await _check(r,(200,))
        rows=await r.json()
        return rows[0] if rows else None


async def set_channel(guild_id: int, field: str, channel_id: int):
    allowed={"offensive_channel_id","defensive_channel_id","spy_channel_id"}
    if field not in allowed:
        raise ValueError("Unsupported sphere channel field")
    payload={"guild_id":guild_id,field:channel_id}
    async with database._session.post(_base()+"/sphere_config?on_conflict=guild_id",json=payload,headers=_headers("resolution=merge-duplicates,return=minimal")) as r:
        await _check(r)


async def get_spy_baseline(guild_id: int, nation_id: int) -> int | None:
    async with database._session.get(_base()+"/sphere_spy_tracking",params={"guild_id":f"eq.{guild_id}","nation_id":f"eq.{nation_id}","select":"last_known_spies"}) as r:
        await _check(r,(200,))
        rows=await r.json()
        return rows[0]["last_known_spies"] if rows else None


async def set_spy_baseline(guild_id: int, alliance_id: int, nation_id: int, nation_name: str, spies: int):
    payload={"guild_id":guild_id,"alliance_id":alliance_id,"nation_id":nation_id,"nation_name":nation_name,"last_known_spies":spies}
    async with database._session.post(_base()+"/sphere_spy_tracking?on_conflict=guild_id,nation_id",json=payload,headers=_headers("resolution=merge-duplicates,return=minimal")) as r:
        await _check(r)


async def upsert_war(guild_id: int, alliance_id: int, alliance_name: str, war: dict):
    payload={"guild_id":guild_id,"alliance_id":alliance_id,"alliance_name":alliance_name,"war_id":war["id"],"war_type":war.get("war_type"),"turns_left":war.get("turns_left"),"attacker_nation_id":(war.get("attacker") or {}).get("id"),"attacker_name":(war.get("attacker") or {}).get("nation_name"),"attacker_alliance_id":(war.get("attacker") or {}).get("alliance_id"),"defender_nation_id":(war.get("defender") or {}).get("id"),"defender_name":(war.get("defender") or {}).get("nation_name"),"defender_alliance_id":(war.get("defender") or {}).get("alliance_id"),"last_seen_at":"now()"}
    # PostgREST cannot accept SQL expressions as JSON values; use a normal
    # timestamp generated by the application instead.
    from datetime import datetime, timezone
    payload["last_seen_at"]=datetime.now(timezone.utc).isoformat()
    async with database._session.post(_base()+"/sphere_wars?on_conflict=guild_id,alliance_id,war_id",json=payload,headers=_headers("resolution=merge-duplicates,return=minimal")) as r:
        await _check(r)


async def mark_war_alerted(guild_id: int, alliance_id: int, war_id: int, field: str):
    if field not in {"offensive_alerted","defensive_alerted"}:
        raise ValueError("Unsupported war alert field")
    from datetime import datetime, timezone
    payload={field:True,"updated_at":datetime.now(timezone.utc).isoformat()}
    async with database._session.patch(_base()+"/sphere_wars",params={"guild_id":f"eq.{guild_id}","alliance_id":f"eq.{alliance_id}","war_id":f"eq.{war_id}"},json=payload) as r:
        await _check(r)


async def was_war_alerted(guild_id: int, alliance_id: int, war_id: int, field: str) -> bool:
    async with database._session.get(_base()+"/sphere_wars",params={"guild_id":f"eq.{guild_id}","alliance_id":f"eq.{alliance_id}","war_id":f"eq.{war_id}","select":field}) as r:
        await _check(r,(200,))
        rows=await r.json()
        return bool(rows and rows[0].get(field))


async def find_recent_offensive_against(guild_id: int, nation_id: int, since_iso: str) -> dict | None:
    """Look for a sphere war, seen since `since_iso`, where `nation_id` was the
    DEFENDER — i.e. a nation in one of our registered sphere alliances attacked
    them. Used to label an incoming defensive war as a likely counter-attack.

    Returns the most recently seen matching war row, or None if there isn't one.
    `since_iso` should be a recent window (the monitor refreshes every active
    war's last_seen_at each cycle, so an ended war's last_seen_at stops moving
    forward and naturally falls out of a short window).
    """
    params = {
        "guild_id": f"eq.{guild_id}",
        "defender_nation_id": f"eq.{nation_id}",
        "last_seen_at": f"gte.{since_iso}",
        "select": "war_id,alliance_name,attacker_name,attacker_alliance_id,last_seen_at",
        "order": "last_seen_at.desc",
        "limit": "1",
    }
    async with database._session.get(_base()+"/sphere_wars", params=params) as r:
        await _check(r, (200,))
        rows = await r.json()
        return rows[0] if rows else None
